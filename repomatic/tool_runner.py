GENERATED_HEADER_TEMPLATE = (
    "Generated by {command} v{version} - https://github.com/kdeldycke/repomatic"
)
"""Template for the first line of generated-file headers.

Used by both CLI commands (e.g. `sync-mailmap`) and the tool runner
(e.g. `run shfmt`) to stamp files with provenance.  Format fields:
`command` (full command path) and `version` (package version).
"""


def generated_header(command: str, comment_prefix: str = "# ") -> str:
    """Return a generated-by header block with timestamp.

    :param command: Full command path (e.g. `repomatic sync-mailmap`).
    :param comment_prefix: Comment prefix for the target format.
    """
    line1 = GENERATED_HEADER_TEMPLATE.format(command=command, version=__version__)
    line2 = f"Timestamp: {datetime.now(tz=timezone.utc).isoformat()}"
    return f"{comment_prefix}{line1}\n{comment_prefix}{line2}\n"


class ArchiveFormat(Enum):
    """Archive format for binary tool downloads."""

    RAW = "raw"
    TAR_GZ = "tar.gz"
    TAR_XZ = "tar.xz"
    ZIP = "zip"

    def tarfile_mode(self) -> Literal["r:gz", "r:xz"]:
        """Return the `tarfile.open` mode string for this format.

        :raises ValueError: If called on a non-tar format.
        """
        if self is ArchiveFormat.TAR_GZ:
            return "r:gz"
        if self is ArchiveFormat.TAR_XZ:
            return "r:xz"
        msg = f"{self.value} is not a tar archive"
        raise ValueError(msg)

    def extract(
        self,
        archive_path: Path,
        spec: BinarySpec,
        dest_dir: Path,
        executable: str,
    ) -> Path:
        """Extract *executable* from *archive_path* in this format.

        A `RAW` download is the executable itself and is renamed into place;
        the archive formats delegate to their extractors.

        :param archive_path: Path to the downloaded archive file.
        :param spec: Binary specification with executable path info.
        :param dest_dir: Directory to extract into.
        :param executable: Executable filename to extract.
        :return: Path to the extracted executable.
        :raises FileNotFoundError: If the executable is not in the archive.
        """
        if self is ArchiveFormat.RAW:
            dest = dest_dir / executable
            archive_path.rename(dest)
            dest.chmod(0o755)
            return dest
        if self is ArchiveFormat.ZIP:
            return _extract_from_zip(archive_path, spec, dest_dir, executable)
        return _extract_from_tar(archive_path, self, spec, dest_dir, executable)


class NativeFormat(Enum):
    """Target format for `[tool.X]` translation."""

    YAML = "yaml"
    TOML = "toml"
    JSON = "json"
    EDITORCONFIG = "editorconfig"
    # Not a file format: translate the table to CLI flags via
    # `pyproject_table_to_flags` and pass them on the command line.
    FLAGS = "flags"

    def _header(self, tool_name: str) -> str:
        """Return a generated-by header block in this format's comment syntax.

        JSON has no standard comment syntax, so returns an empty string.
        """
        if self is NativeFormat.JSON:
            return ""
        # YAML, TOML, and editorconfig all use `#` comments.
        return generated_header(f"repomatic run {tool_name}")

    def serialize(self, data: dict, tool_name: str = "") -> str:
        """Serialize a config dict to this format's string representation.

        When *data* is a live `[tool.X]` table parsed from `pyproject.toml`
        (a `tomlrt.Table`), the TOML branch keeps the user's comments by
        reparenting the section to the document root; see
        `_reroot_section`. A plain dict carries no trivia, so it is
        rendered as-is. The other formats (YAML, JSON, editorconfig) cannot
        carry TOML comments across the format boundary, so they serialize the
        values only.

        :param data: Configuration dictionary to serialize.
        :param tool_name: Tool name for the generated-by header comment.
        :raises ValueError: For `FLAGS`, which is not a file format.
        """
        if self is NativeFormat.FLAGS:
            msg = "FLAGS is not a file format; use pyproject_table_to_flags()."
            raise ValueError(msg)
        header = self._header(tool_name) if tool_name else ""
        # Only the TOML serializer can consume a live `tomlrt.Table` and keep its
        # comments; YAML/JSON/editorconfig need plain Python types (their
        # encoders key on exact types and choke on tomlrt's table and array).
        if self is not NativeFormat.TOML and isinstance(data, tomlrt.Table):
            data = data.to_dict()
        if self is NativeFormat.YAML:
            return header + yaml.safe_dump(
                data, default_flow_style=False, sort_keys=False
            )
        if self is NativeFormat.TOML:
            doc = (
                _reroot_section(data)
                if isinstance(data, tomlrt.Table)
                else tomlrt.Document(data)
            )
            return header + doc.render()
        if self is NativeFormat.EDITORCONFIG:
            return self._serialize_editorconfig(data, header)
        return json.dumps(data, indent=2) + "\n"

    @staticmethod
    def _serialize_editorconfig(data: dict, header: str) -> str:
        """Serialize a flat dict to editorconfig format.

        Emits all keys under `[*]` (match-all glob). TOML-style hyphens in
        key names are converted to underscores (editorconfig convention).
        """
        lines = [f"{header}root = true", "", "[*]"]
        for key, value in data.items():
            ec_key = key.replace("-", "_")
            if isinstance(value, bool):
                lines.append(f"{ec_key} = {str(value).lower()}")
            else:
                lines.append(f"{ec_key} = {value}")
        return "\n".join(lines) + "\n"


def _reroot_section(section: tomlrt.Table) -> tomlrt.Document:
    """Reparent a `[tool.X]` section to a standalone TOML document.

    A native config file (`.gitleaks.toml`) drops the `[tool.X]` prefix the
    section carries inside `pyproject.toml`: top-level keys move to the document
    root and every `[tool.X.sub]` header becomes `[sub]`. Assigning each value
    into a fresh `Document` routes sub-tables and arrays-of-tables through
    tomlrt's trivia-preserving clone path (dimbleby/tomlrt#171), so their
    comments and nested headers survive. Direct scalar and array keys lose their
    key-level trivia on that assignment (the trivia lives on the parent slot,
    not the value), so the leading block and end-of-line comment are copied back
    explicitly.

    ```{note}
    End-of-line comments are re-emitted with a single space before `#`,
    normalising any wider padding from the source. A comment on the `[tool.X]`
    header line itself has no home at the document root and is dropped.
    ```

    :param section: A live `[tool.X]` table parsed from `pyproject.toml`.
    :return: A standalone document with the section's body at the root.
    """
    # An inline `tool.x = {...}` table holds no standalone comments, and the
    # comment API is unavailable on it; expand to a plain document, matching the
    # behaviour before trivia preservation.
    if section.is_inline:
        return tomlrt.Document(section.to_dict())
    doc = tomlrt.Document()
    for key in section:
        doc[key] = section[key]
    # Sub-tables and AoTs carry their own trivia through the assignment above;
    # only direct scalar and array KV trivia needs restoring.
    for key, value in section.items():
        if isinstance(value, (tomlrt.Table, tomlrt.AoT)):
            continue
        if leading := section.leading_block.get(key):
            doc.leading_block[key] = leading
        if eol := section.comments.get(key):
            doc.comments[key] = eol
    return doc


PlatformKey = tuple[Platform | Group, Architecture]
"""A `(platform_or_group, architecture)` pair used as binary lookup key.

The platform element can be a single {class}`~extra_platforms.Platform` (like
`MACOS`) or a {class}`~extra_platforms.Group` (like `LINUX`, which matches
any Linux distribution). The architecture is always a concrete
{class}`~extra_platforms.Architecture`.

Resolution order in {meth}`BinarySpec.resolve_platform`:

1. Exact Platform match (`current_platform() == key_platform`).
2. Group membership (`current_platform() in key_group`), preferring the
   group with fewest members (most specific).
"""


@dataclass(frozen=True)
class BinarySpec:
    """Platform-specific binary download specification.

    Keys are {data}`PlatformKey` tuples pairing an extra-platforms
    {class}`~extra_platforms.Platform` or {class}`~extra_platforms.Group`
    with an {class}`~extra_platforms.Architecture`. This lets callers use
    broad groups (`LINUX` matches any distro) or specific platforms
    (`DEBIAN`) with full detection heuristics from extra-platforms.

    ```{hint}
    Structural integrity checks (key types, checksum format, URL
    placeholders, strip_components consistency) are enforced in
    `test_tool_spec_integrity`. If the registry becomes
    user-configurable in the future, move these checks to
    `__post_init__`.
    ```
    """

    urls: dict[PlatformKey, str]
    """Platform key to URL template mapping. URLs use ``{version}`` placeholders."""

    checksums: dict[PlatformKey, str]
    """Platform key to SHA-256 hex digest mapping."""

    archive_format: ArchiveFormat | dict[PlatformKey | Platform | Group, ArchiveFormat]
    """Archive format of the downloaded file.

    A single {class}`ArchiveFormat` applies to every platform. A dict maps
    platform specifiers to formats, allowing mixed archives in one spec::

        archive_format={ALL_PLATFORMS: ArchiveFormat.TAR_GZ, WINDOWS: ArchiveFormat.ZIP}

    Dict keys follow the same resolution as {meth}`resolve_platform`:
    exact {data}`PlatformKey` tuple first, then bare
    {class}`~extra_platforms.Platform` equality, then
    {class}`~extra_platforms.Group` membership (smallest group wins).
    """

    archive_executable: str | None = None
    """Path of the executable inside the archive. `None` defaults to the
    tool name. For `RAW` format, used as the final filename.
    """

    strip_components: int = 0
    """Number of leading path components to strip when extracting."""

    def resolve_platform(self) -> PlatformKey:
        """Match the current environment against registered platform keys.

        Uses `current_platform()` and `current_architecture()` from
        extra-platforms, inheriting its full detection heuristics.

        :return: The matching {data}`PlatformKey`.
        :raises RuntimeError: If no key matches the current environment.
        """
        arch = current_architecture()
        plat = current_platform()

        # Pass 1: exact Platform match (highest priority).
        for key_plat, key_arch in self.urls:
            if key_arch == arch and isinstance(key_plat, Platform) and key_plat == plat:
                return (key_plat, key_arch)

        # Pass 2: Group membership (prefer smallest group = most specific).
        candidates: list[tuple[Group, Architecture]] = []
        for key_plat, key_arch in self.urls:
            if key_arch == arch and isinstance(key_plat, Group) and plat in key_plat:
                candidates.append((key_plat, key_arch))

        if len(candidates) == 1:
            return candidates[0]
        if candidates:
            # Most-specific group: fewest members.
            return min(candidates, key=lambda c: len(c[0]))

        available = ", ".join(
            f"{k[0].name} {k[1].name}" for k in sorted(self.urls, key=str)
        )
        msg = f"No binary for {plat.name} {arch.name}. Available: {available}."
        raise RuntimeError(msg)

    def get_archive_format(self, key: PlatformKey) -> ArchiveFormat:
        """Return the archive format for the given platform key.

        When `archive_format` is a single {class}`ArchiveFormat`, returns
        it directly. When it is a dict, resolves in order: exact
        {data}`PlatformKey` tuple, bare Platform equality, then Group
        membership (smallest group wins).
        """
        if isinstance(self.archive_format, ArchiveFormat):
            return self.archive_format

        fmt_map = self.archive_format

        # Exact tuple match.
        if key in fmt_map:
            return fmt_map[key]

        # Bare Platform or Group match.
        key_plat = key[0]
        group_hits: list[tuple[Group, ArchiveFormat]] = []
        for map_key, fmt in fmt_map.items():
            if isinstance(map_key, tuple):
                continue
            if map_key == key_plat:
                return fmt
            if isinstance(map_key, Group) and (
                isinstance(key_plat, Platform)
                and key_plat in map_key
                or isinstance(key_plat, Group)
                and (key_plat & map_key)
            ):
                group_hits.append((map_key, fmt))

        if group_hits:
            # Most-specific group: fewest members.
            return min(group_hits, key=lambda h: len(h[0]))[1]

        msg = f"No archive format for {key[0].name} {key[1].name}"
        raise ValueError(msg)

    @staticmethod
    def platform_cache_key(key: PlatformKey) -> str:
        """Derive a filesystem-safe cache path segment from a platform key.

        :return: A string like `linux-aarch64` or `macos-x86_64`.
        """
        return f"{key[0].id}-{key[1].id}"


NPM_MIN_VERSION_FOR_COOLDOWN = "11.10.0"
"""First npm release honoring `min-release-age`, the cooldown gate for npm tools.

Older npm silently ignores the `--min-release-age` flag, so {func}`_install_npm`
warns when it cannot enforce the cooldown. This is a fixed floor (the release that
introduced the option), distinct from the auto-bumped `npm@X` bootstrap pin in
`lint.yaml`, which tracks the latest npm.
"""


@dataclass(frozen=True)
class NpmSpec:
    """npm-registry backend marker for a {class}`ToolSpec`.

    Presence (`ToolSpec.npm is not None`) selects the npm backend, the way a
    {class}`BinarySpec` selects the download backend. The package name,
    executable, and version all derive from the `ToolSpec` fields, so no per-tool
    npm config is needed today; the class exists as a typed discriminator and a
    home for future npm-specific options.

    ```{note}
    npm tools need Node.js and npm on `PATH` at run time: the one backend that
    depends on a runtime repomatic neither bundles nor provisions (binary tools
    are self-contained; the uv backends use uv). Integrity is npm's own
    per-tarball verification on install, so unlike {class}`BinarySpec` there is
    no repomatic-pinned checksum; the `minimum-release-age` cooldown (npm's
    `min-release-age`, npm 11.10.0+) gates the transitive tree instead. Older npm
    ignores the gate, so the runner warns rather than silently skipping it.
    ```
    """


@dataclass(frozen=True)
class ToolSpec:
    """Specification for an external tool managed by repomatic.

    ```{hint}
    Structural integrity checks (name format, version format, flag
    conventions, field consistency) are enforced in
    `test_tool_spec_integrity`. If the registry becomes user-configurable
    in the future, move these checks to `__post_init__`.
    ```

    ```{hint} CLI parser quirks for `config_after_subcommand`

    Tools that use subcommands (`tool <subcmd> [flags] [files]`) may
    require `config_flag` to appear after the subcommand name, depending
    on the CLI parser framework:

    - **clap** (Rust): global flags accepted before or after the
      subcommand. No special handling needed. Used by: ruff, labelmaker.
    - **cobra** (Go): root-level flags inherited by all subcommands,
      accepted in both positions. No special handling needed.
      Used by: gitleaks.
    - **click** (Python): global flags accepted before or after the
      subcommand. No special handling needed. Used by: bump-my-version.
    - **bpaf** (Rust): `#[bpaf(external)]` fields are scoped inside
      the subcommand variant, so `tool <subcmd> --flag` works but
      `tool --flag <subcmd>` does not. Set
      `config_after_subcommand=True`. Used by: biome.
    ```
    """

    name: str
    """Tool identity: CLI name for `repomatic run <name>`, default PyPI
    package name, and default executable name.
    """

    display_name: str | None = None
    """Human-readable name with proper casing for documentation (like
    `'Biome'`, `'Gitleaks'`). `None` defaults to `name`.
    """

    version: str = ""
    """Pinned version (e.g., `'1.38.0'`)."""

    package: str | None = None
    """Install target passed to `uvx`/`uv run` (and pip). `None` defaults to
    `name`. Only set when it differs from the tool name, and may carry an
    install extra (Nuitka's `nuitka[onefile]`); for PyPI lookups query the bare
    project name through {attr}`pypi_name`, which strips the extra.
    """

    executable: str | None = None
    """Executable name if different from the tool name. `None` defaults to
    the registry key.
    """

    module: str | None = None
    """Python module name for `-m module` invocation, e.g. `'nuitka'`.

    When set, the tool is invoked as `python -m <module>` instead of the
    console script. Requires `needs_venv=True`. Use when the tool's script
    entry point is not reliably found across platforms (for example, Nuitka
    installs only a `.cmd` wrapper on Windows, which `uv run -- nuitka` cannot
    locate).
    """

    native_config_files: tuple[str, ...] = ()
    """Config filenames the tool auto-discovers, checked in order.

    Paths relative to repo root (e.g., `'zizmor.yaml'`,
    `'.github/actionlint.yaml'`). Empty for tools with no config file.
    """

    config_flag: str | None = None
    """CLI flag to pass a config file path (e.g., `'--config'`,
    `'--config-file'`). `None` if the tool only reads from fixed paths.
    """

    native_format: NativeFormat = NativeFormat.YAML
    """Target format for `[tool.X]` translation.

    `NativeFormat.FLAGS` translates the table to CLI flags (via
    `pyproject_table_to_flags`) instead of a config file, for tools that expose
    their config keys as long options but read no config file themselves. It is
    mutually exclusive with `reads_pyproject`, `config_flag`, and
    `native_config_files`.
    """

    default_config: str | None = None
    """Filename in `repomatic/data/` for bundled defaults, stored in
    `native_format`. `None` if no bundled default exists.
    """

    reads_pyproject: bool = False
    """Whether the tool natively reads `[tool.X]` from `pyproject.toml`.

    When `True` and `[tool.X]` exists in `pyproject.toml`, repomatic
    skips Level 2 translation (the tool reads it directly). Resolution still
    falls through to Level 3 (bundled default) and Level 4 (bare) when no
    config is found.
    """

    default_flags: tuple[str, ...] = ()
    """Flags always passed to the tool (e.g., `('--strict',)`)."""

    ci_flags: tuple[str, ...] = ()
    """Flags added only when `$GITHUB_ACTIONS` is set (e.g., output format)."""

    with_packages: tuple[str, ...] = ()
    """Extra packages installed alongside the tool (e.g., mdformat plugins).

    Passed as `--with <pkg>` to uvx.
    """

    needs_venv: bool = False
    """If `True`, use `uv run` (project venv) instead of `uvx` (isolated).

    Required when the tool imports project code (mypy, pytest).
    """

    computed_params: Callable[[Metadata], list[str]] | None = None
    """Callable that receives a `Metadata` instance and returns extra CLI args
    derived from project metadata (e.g., mypy's `--python-version` from
    `requires-python`). `None` if no computed params.
    """

    config_after_subcommand: bool = False
    """Insert `config_flag` after the first token of `extra_args`.

    Needed for tools whose CLI parser (e.g., bpaf) scopes global options inside
    the subcommand, so `tool subcommand --config-path X` is valid but
    `tool --config-path X subcommand` is not. When `True`, `config_args`
    are spliced after the first element of `extra_args` (the subcommand name).
    """

    post_process: Callable[[Sequence[str]], None] | None = None
    """Callback invoked on `extra_args` after the tool exits successfully.

    Intended for temporary workarounds that fix known upstream formatting bugs
    in-place. Remove the callback once upstream ships the fix.

    ```{note}
    The callback runs only after a successful **write-mode** exit (return
    code 0) and rewrites files on disk, so it cannot apply in check/dry-run
    mode, which writes nothing. Pair it with `check_flags` so `run_tool`
    warns when a check invocation would silently bypass it. See
    {meth}`check_bypasses_post_process`.
    ```
    """

    check_flags: tuple[str, ...] = ()
    """Flags that put the tool in check/dry-run mode, writing no files.

    ```{warning}
    Check mode bypasses `post_process`: that fixup rewrites files on disk,
    but check mode writes nothing. So when a tool defines both a
    `post_process` and `check_flags`, its check-mode exit status is
    unreliable. `run_tool` detects the pairing via
    {meth}`check_bypasses_post_process` and warns. Verify formatting by
    running the write path, not the check flag.
    ```
    """

    binary: BinarySpec | None = None
    """Platform-specific binary download spec. When set, the tool is downloaded
    as a binary instead of installed via `uvx` or `uv run`.
    """

    npm: NpmSpec | None = None
    """npm-registry backend marker. When set, the tool is installed from npm and
    run via its `node_modules/.bin` executable, instead of a binary download or a
    uv install. Mutually exclusive with `binary` and `needs_venv`.
    """

    source_url: str | None = None
    """GitHub repository or project homepage URL."""

    tag_pattern: str | None = None
    """Regex extracting the version from a GitHub release tag.

    Used by `sync-tool-versions` for binary tools whose tags do not follow the
    common `vX.Y.Z` scheme. The pattern must define a `version` named group
    (e.g. `r"^lychee-v(?P<version>.+)$"` for lychee, `r"^@biomejs/biome@
    (?P<version>.+)$"` for biome). When `None`, the version is the tag with a
    leading `v` stripped.
    """

    config_docs_url: str | None = None
    """URL to the tool's configuration reference."""

    cli_docs_url: str | None = None
    """URL to the tool's CLI usage documentation."""

    docs_notes: str = ""
    """Hand-written Markdown appended to the tool's section in `tool-runner.md`.

    Free-form usage notes the registry cannot derive: a `**Try it:**` shell
    session, a minimal `[tool.X]` example, caveats. Rendered live by
    `repomatic.tool_runner_page.tool_reference` after the generated metadata
    lines, so the prose stays next to the spec it documents.
    """

    @property
    def pypi_name(self) -> str:
        """Bare PyPI project name for version and metadata lookups.

        {attr}`package` doubles as the install target, so it may carry an
        install extra (Nuitka's `nuitka[onefile]`) that `_build_install_args`
        needs at install time. The PyPI JSON API is keyed by the bare project
        name, though, and 404s on a bracketed extra, so `sync-tool-versions`
        and the held-back PR links query this stripped name (`nuitka`) instead.
        """
        return Requirement(self.package or self.name).name

    @property
    def datasource_url(self) -> str:
        """Human-facing URL for the tool's version datasource.

        npmjs for npm tools, the GitHub `source_url` when set, else the PyPI
        project page. Used by `sync-tool-versions` for the diff-table and
        held-back links.
        """
        if self.npm is not None:
            return f"https://www.npmjs.com/package/{self.package or self.name}"
        if self.source_url:
            return self.source_url
        return f"https://pypi.org/project/{self.pypi_name}/"

    def check_bypasses_post_process(self, extra_args: Sequence[str]) -> bool:
        """Return `True` when a check-mode flag will skip `post_process`.

        Check/dry-run flags (`check_flags`) make the tool exit without
        writing files, so the `post_process` fixup never runs and the exit
        status cannot be trusted: it may flag drift the write path would
        reconcile, or miss drift the write path would introduce. `run_tool`
        warns on this. Returns `False` for tools with no `post_process`,
        where check mode is authoritative.
        """
        return bool(self.post_process) and any(
            flag in extra_args for flag in self.check_flags
        )


