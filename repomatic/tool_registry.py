@dataclass(frozen=True)
class NpmSpec:
    """npm-registry backend marker for a {class}`ToolSpec`.

    Presence (`ToolSpec.npm is not None`) selects the npm backend, the way a
    {class}`BinarySpec` selects the download backend. The package name,
    executable, and version all derive from the `ToolSpec` fields, so no per-tool
    npm config is needed today; the class exists as a typed discriminator and a
    home for future npm-specific options.

    ```{note}
    npm tools need Node.js and npm on `PATH` at run time: the one backend that
    depends on a runtime repomatic neither bundles nor provisions (binary tools
    are self-contained; the uv backends use uv). Integrity is npm's own
    per-tarball verification on install, so unlike {class}`BinarySpec` there is
    no repomatic-pinned checksum; the `minimum-release-age` cooldown (npm's
    `min-release-age`, npm 11.10.0+) gates the transitive tree instead. Older npm
    ignores the gate, so the runner warns rather than silently skipping it.
    ```
    """


@dataclass(frozen=True)
class ToolSpec:
    """Specification for an external tool managed by repomatic.

    ```{hint}
    Structural integrity checks (name format, version format, flag
    conventions, field consistency) are enforced in
    `test_tool_spec_integrity`.
    ```

    ```{todo}
    Move those integrity checks to `__post_init__` if the registry ever becomes
    user-configurable: a test only covers the specs shipped here.
    ```

    ```{hint} CLI parser quirks for `config_after_subcommand`

    Tools that use subcommands (`tool <subcmd> [flags] [files]`) may
    require `config_flag` to appear after the subcommand name, depending
    on the CLI parser framework:

    - **clap** (Rust): global flags accepted before or after the
      subcommand. No special handling needed. Used by: ruff, labelmaker.
    - **cobra** (Go): root-level flags inherited by all subcommands,
      accepted in both positions. No special handling needed.
      Used by: gitleaks.
    - **click** (Python): global flags accepted before or after the
      subcommand. No special handling needed. Used by: bump-my-version.
    - **bpaf** (Rust): `#[bpaf(external)]` fields are scoped inside
      the subcommand variant, so `tool <subcmd> --flag` works but
      `tool --flag <subcmd>` does not. Set
      `config_after_subcommand=True`. Used by: biome.
    ```
    """

    name: str
    """Tool identity: CLI name for `repomatic run <name>`, default PyPI
    package name, and default executable name.
    """

    display_name: str | None = None
    """Human-readable name with proper casing for documentation (like
    `'Biome'`, `'Gitleaks'`). `None` defaults to `name`.
    """

    version: str = ""
    """Pinned version (e.g., `'1.38.0'`)."""

    package: str | None = None
    """Install target passed to `uvx`/`uv run` (and pip). `None` defaults to
    `name`. Only set when it differs from the tool name, and may carry an
    install extra (Nuitka's `nuitka[onefile]`); for PyPI lookups query the bare
    project name through {attr}`pypi_name`, which strips the extra.
    """

    executable: str | None = None
    """Executable name if different from the tool name. `None` defaults to
    the registry key.
    """

    module: str | None = None
    """Python module name for `-m module` invocation, e.g. `'nuitka'`.

    When set, the tool is invoked as `python -m <module>` instead of the
    console script. Requires `needs_venv=True`. Use when the tool's script
    entry point is not reliably found across platforms (for example, Nuitka
    installs only a `.cmd` wrapper on Windows, which `uv run -- nuitka` cannot
    locate).
    """

    native_config_files: tuple[str, ...] = ()
    """Config filenames the tool auto-discovers, checked in order.

    Paths relative to repo root (e.g., `'zizmor.yaml'`,
    `'.github/actionlint.yaml'`). Empty for tools with no config file.
    """

    config_flag: str | None = None
    """CLI flag to pass a config file path (e.g., `'--config'`,
    `'--config-file'`). `None` if the tool only reads from fixed paths.
    """

    native_format: NativeFormat = NativeFormat.YAML
    """Target format for `[tool.X]` translation.

    `NativeFormat.FLAGS` translates the table to CLI flags (via
    `config_table_to_flags`) instead of a config file, for tools that expose
    their config keys as long options but read no config file themselves. It is
    mutually exclusive with `reads_pyproject`, `config_flag`, and
    `native_config_files`.
    """

    default_config: str | None = None
    """Filename in `repomatic/data/` for bundled defaults, stored in
    `native_format`. `None` if no bundled default exists.
    """

    reads_pyproject: bool = False
    """Whether the tool natively reads `[tool.X]` from `pyproject.toml`.

    When `True` and `[tool.X]` exists in `pyproject.toml`, repomatic
    skips Level 2 translation (the tool reads it directly). Resolution still
    falls through to Level 3 (bundled default) and Level 4 (bare) when no
    config is found.
    """

    default_flags: tuple[str, ...] = ()
    """Flags always passed to the tool (e.g., `('--strict',)`)."""

    ci_flags: tuple[str, ...] = ()
    """Flags added only when `$GITHUB_ACTIONS` is set (e.g., output format)."""

    default_args: tuple[str, ...] = ()
    """Arguments used when the caller passes none of their own.

    Together with {attr}`default_paths`, this makes a bare
    `repomatic run <tool>` the invocation CI performs, so nobody has to
    reconstruct it from a workflow step. It applies **only** when
    `extra_args` is empty: any explicit argument means the caller is
    driving, and nothing is injected on top of it.

    That all-or-nothing rule is what keeps a subcommand safe to put here.
    biome's defaults open with `format`, and splicing them into a caller's
    `check .` would build `biome format … check .`; because an explicit
    argument suppresses them entirely, that command cannot be built.
    """

    default_paths: str | None = None
    """Name of the {class}`~repomatic.file_inventory.FileInventory` attribute
    supplying this tool's targets, when the caller passes no arguments.

    ```{caution}
    An empty inventory means the tool is **skipped**, not invoked with no
    path. The distinction is the whole point: a formatter handed zero paths
    does not no-op, it walks the entire tree in write mode. Replaying a
    workflow's `xargs` pipe on a repo with no matching file did exactly
    that once, rewriting 3,000+ files, and it is the reason this resolves
    the list in-process rather than leaving it to a shell.
    ```
    """

    per_file: bool = False
    """Invoke the tool once per target rather than once for all of them.

    Mirrors `xargs -n1`, for a tool whose per-file behaviour differs from its
    batch behaviour. Only meaningful alongside {attr}`default_paths`.
    """

    with_packages: tuple[str, ...] = ()
    """Extra packages installed alongside the tool (e.g., mdformat plugins).

    Passed as `--with <pkg>` to uvx.
    """

    path_tools: tuple[str, ...] = ()
    """Other registry tools whose executable must be on `PATH` while this runs.

    For a plugin that shells out to a second binary rather than importing it:
    `mdformat-shfmt` formats fenced shell blocks by invoking `shfmt` from `PATH`,
    so `mdformat` declares `path_tools=("shfmt",)`.

    Each name is installed through the same registry path as a direct
    `repomatic run`, so the companion arrives at the pinned version, checksum
    verified, from the shared cache. The alternative, letting the environment
    supply it, is what this field exists to prevent: a system package manager
    hands over whatever its archive holds, unpinned and outside the cooldown, and
    the same tool then behaves differently depending on which job invoked it.

    Names must resolve in {data}`TOOL_REGISTRY` and carry a `binary` spec;
    `test_tool_spec_integrity` enforces both.
    """

    needs_venv: bool = False
    """If `True`, use `uv run` (project venv) instead of `uvx` (isolated).

    Required when the tool imports project code (mypy, pytest). The project
    venv materializes from the frozen `uv.lock`; in a repository without one
    the runner degrades to an isolated, cooldown-gated environment
    (`uv run --no-project`), see `_build_install_args` in `tool_runner.py`.
    """

    computed_params: Callable[[Metadata], list[str]] | None = None
    """Callable that receives a `Metadata` instance and returns extra CLI args
    derived from project metadata (e.g., mypy's `--python-version` from
    `requires-python`). `None` if no computed params.
    """

    config_after_subcommand: bool = False
    """Insert `config_flag` after the first token of `extra_args`.

    Needed for tools whose CLI parser (e.g., bpaf) scopes global options inside
    the subcommand, so `tool subcommand --config-path X` is valid but
    `tool --config-path X subcommand` is not. When `True`, `config_args`
    are spliced after the first element of `extra_args` (the subcommand name).
    """

    post_process: Callable[[Sequence[str]], None] | None = None
    """Callback invoked on `extra_args` after the tool exits successfully.

    Intended for temporary workarounds that fix known upstream formatting bugs
    in-place. Each callback carries its own todo admonition naming the upstream
    release that retires it.

    ```{note}
    The callback runs only after a successful **write-mode** exit (return
    code 0) and rewrites files on disk, so it cannot apply in check/dry-run
    mode, which writes nothing. Pair it with `check_flags` so `run_tool`
    warns when a check invocation would silently bypass it. See
    {meth}`check_bypasses_post_process`.
    ```
    """

    output_flag: str | None = None
    """Flag whose argument names the tool's report destination, when the tool
    refuses to create missing parent directories itself.

    `run_tool` pre-creates the parent directory of the path following this
    flag (both `--flag path` and `--flag=path` forms), so a workflow can point
    the tool into a scratch subdirectory without a separate `mkdir` step.
    lychee is the motivating case: `docs.yaml` collects its report from a
    dedicated subdirectory, and lychee errors out rather than creating it.
    """

    check_flags: tuple[str, ...] = ()
    """Flags that put the tool in check/dry-run mode, writing no files.

    ```{warning}
    Check mode bypasses `post_process`: that fixup rewrites files on disk,
    but check mode writes nothing. So when a tool defines both a
    `post_process` and `check_flags`, its check-mode exit status is
    unreliable. `run_tool` detects the pairing via
    {meth}`check_bypasses_post_process` and warns. Verify formatting by
    running the write path, not the check flag:
    {func}`repomatic.tool_runner.verify_via_write_path` does exactly that
    against throwaway copies, so the answer is authoritative and the working
    tree is still never written to.
    ```
    """

    rewrite_exit_code: int | None = None
    """Exit code the tool returns when it rewrote at least one file.

    Formatters that signal "I reformatted something" with a non-zero status
    force every caller to tolerate that code, which is what lets a crash pass
    for a success: pyproject-fmt exits `1` both when it reformats a file and
    when it dies on a `PanicException`, and the autofix job cannot tell the two
    apart from the status alone.

    Declaring the code here gives `run_tool` the second signal it needs: the
    files themselves. A run exiting with this code and leaving every target
    byte-identical contradicts what the code claims, so it is reported as a
    failure instead of being waved through. See
    {data}`repomatic.tool_runner.TOOL_CRASH_EXIT_CODE`.

    `None` for tools with no such convention, which is most of them: a
    formatter that exits `0` whether or not it wrote anything needs no
    disambiguation.
    """

    binary: BinarySpec | None = None
    """Platform-specific binary download spec. When set, the tool is downloaded
    as a binary instead of installed via `uvx` or `uv run`.
    """

    npm: NpmSpec | None = None
    """npm-registry backend marker. When set, the tool is installed from npm and
    run via its `node_modules/.bin` executable, instead of a binary download or a
    uv install. Mutually exclusive with `binary` and `needs_venv`.
    """

    source_url: str | None = None
    """GitHub repository or project homepage URL."""

    tag_pattern: str | None = None
    """Regex extracting the version from a GitHub release tag.

    Used by `sync-tool-versions` for binary tools whose tags do not follow the
    common `vX.Y.Z` scheme. The pattern must define a `version` named group
    (e.g. `r"^lychee-v(?P<version>.+)$"` for lychee, `r"^@biomejs/biome@
    (?P<version>.+)$"` for biome). When `None`, the version is the tag with a
    leading `v` stripped.
    """

    config_docs_url: str | None = None
    """URL to the tool's configuration reference."""

    cli_docs_url: str | None = None
    """URL to the tool's CLI usage documentation."""

    docs_notes: str = ""
    """Hand-written Markdown appended to the tool's section in `tool-runner.md`.

    Free-form usage notes the registry cannot derive: a `**Try it:**` shell
    session, a minimal `[tool.X]` example, caveats. Rendered live by
    {func}`tool_reference` after the generated metadata
    lines, so the prose stays next to the spec it documents.
    """

    @property
    def backend(self) -> ToolBackend:
        """Delivery mechanism, derived from which spec fields are set.

        `binary` and `npm` win over `needs_venv`; `test_tool_spec_integrity`
        keeps the three mutually exclusive so the order never actually
        decides.
        """
        if self.binary is not None:
            return ToolBackend.BINARY
        if self.npm is not None:
            return ToolBackend.NPM
        if self.needs_venv:
            return ToolBackend.VENV
        return ToolBackend.UVX

    @property
    def pypi_name(self) -> str:
        """Bare PyPI project name for version and metadata lookups.

        {attr}`package` doubles as the install target, so it may carry an
        install extra (Nuitka's `nuitka[onefile]`) that `_build_install_args`
        needs at install time. The PyPI JSON API is keyed by the bare project
        name, though, and 404s on a bracketed extra, so `sync-tool-versions`
        and the held-back PR links query this stripped name (`nuitka`) instead.
        """
        return Requirement(self.package or self.name).name

    @property
    def datasource_url(self) -> str:
        """Human-facing URL for the tool's version datasource.

        npmjs for npm tools, the GitHub `source_url` when set, else the PyPI
        project page. Used by `sync-tool-versions` for the diff-table and
        held-back links.
        """
        if self.npm is not None:
            return NPM_PACKAGE_URL.format(package=self.package or self.name)
        if self.source_url:
            return self.source_url
        return PYPI_PACKAGE_URL.format(package=self.pypi_name)

    def check_bypasses_post_process(self, extra_args: Sequence[str]) -> bool:
        """Return `True` when a check-mode flag will skip `post_process`.

        Check/dry-run flags (`check_flags`) make the tool exit without
        writing files, so the `post_process` fixup never runs and the exit
        status cannot be trusted: it may flag drift the write path would
        reconcile, or miss drift the write path would introduce. `run_tool`
        warns on this. Returns `False` for tools with no `post_process`,
        where check mode is authoritative.
        """
        return bool(self.post_process) and any(
            flag in extra_args for flag in self.check_flags
        )


