"""Tests for `repomatic.mailmap`: `.mailmap` parsing and contributor sync."""

from __future__ import annotations

import subprocess
from textwrap import dedent

import pytest
from click.testing import CliRunner

from repomatic.cli.main import repomatic
from repomatic.file_ops import generated_header, strip_generated_header
from repomatic.mailmap import Mailmap, Record


def test_sync_mailmap_bootstraps_missing_file(tmp_path, monkeypatch, hermetic_git):
    """A repository with no `.mailmap` yet gets one created instead of crashing.

    The `--create-if-missing` default path used to read an unbound `content`
    variable when the source file did not exist.
    """
    monkeypatch.chdir(tmp_path)
    subprocess.run(["git", "init", "--quiet"], check=True, encoding="UTF-8")
    subprocess.run(
        ["git", "config", "user.email", "kiwi@example.com"],
        check=True,
        encoding="UTF-8",
    )
    subprocess.run(
        ["git", "config", "user.name", "Kiwi Papaya"], check=True, encoding="UTF-8"
    )
    (tmp_path / "fruit.txt").write_text("papaya\n", encoding="UTF-8")
    subprocess.run(["git", "add", "fruit.txt"], check=True, encoding="UTF-8")
    subprocess.run(
        ["git", "commit", "--quiet", "--message", "Add fruit", "--no-gpg-sign"],
        check=True,
        encoding="UTF-8",
    )

    result = CliRunner().invoke(repomatic, ["sync-mailmap"])

    assert result.exit_code == 0, result.output
    mailmap = (tmp_path / ".mailmap").read_text(encoding="UTF-8")
    assert "Kiwi Papaya" in mailmap


@pytest.mark.parametrize(
    ("mailmap", "args", "message"),
    (
        pytest.param(
            None,
            ("--skip-if-missing", "papaya.mailmap"),
            "papaya.mailmap does not exist, stop the sync process.",
            id="skip-if-missing",
        ),
        pytest.param(
            "Kiwi Papaya <kiwi@example.com>\n",
            (),
            "Nothing to update, stop the sync process.",
            id="up-to-date",
        ),
        pytest.param(None, ("-",), "\nKiwi Papaya <kiwi@example.com>\n", id="stdout"),
    ),
)
def test_sync_mailmap_leaves_the_tree_alone(
    tmp_path, monkeypatch, mailmap, args, message
):
    """A run with nothing to write, or writing to stdout, touches no file."""
    orchard = tmp_path / "orchard"
    orchard.mkdir()
    if mailmap is not None:
        (orchard / ".mailmap").write_text(mailmap, encoding="UTF-8")
    before = {path.name: path.read_bytes() for path in orchard.iterdir()}
    monkeypatch.chdir(orchard)
    monkeypatch.setattr(
        "repomatic.mailmap.list_contributor_identities",
        lambda: {"Kiwi Papaya <kiwi@example.com>"},
    )

    result = CliRunner().invoke(repomatic, ["sync-mailmap", *args])

    assert result.exit_code == 0, result.output
    assert message in result.output
    assert {path.name: path.read_bytes() for path in orchard.iterdir()} == before


def test_strip_generated_header():
    content = dedent("""\
        # Generated by repomatic sync-mailmap v4.4.3 - https://github.com/kdeldycke/repomatic
        # Timestamp: 2024-08-12T08:15:41.083405
        # Format is:
        #   Preferred Name <preferred e-mail> Other Name <other e-mail>
        #
        # Reference: https://git-scm.com/docs/git-blame#_mapping_authors

        GitHub <noreply@github.com>
        """)

    assert strip_generated_header(content) == dedent("""\
        # Format is:
        #   Preferred Name <preferred e-mail> Other Name <other e-mail>
        #
        # Reference: https://git-scm.com/docs/git-blame#_mapping_authors

        GitHub <noreply@github.com>""")


def test_mailmap():
    mailmap = Mailmap()

    mailmap.parse(
        dedent(
            """

            github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com> GitHub Actions <actions@github.com>
            GitHub <noreply@github.com>

            GitHub <noreply@github.com>

            GitHub <noreply@github.com>                   dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>
            GitHub <noreply@github.com>         GitHub <noreply@github.com>
            """  # noqa: E501
        )
    )

    assert mailmap.render() == dedent(
        """\
        GitHub <noreply@github.com>
        GitHub <noreply@github.com>
        GitHub <noreply@github.com> dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>
        GitHub <noreply@github.com>
        github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com> GitHub Actions <actions@github.com>"""  # noqa: E501
    )


def test_new_entry():
    mailmap = Mailmap()

    header = dedent(
        """\
        # Generated by repomatic sync-mailmap v4.16.2 - https://github.com/kdeldycke/repomatic
        # Timestamp: 2025-05-13T13:14:51.128939
        # Format is:
        #   Preferred Name <preferred e-mail> Other Name <other e-mail>
        #
        # Reference: https://git-scm.com/docs/git-blame#_mapping_authors"""
    )

    mailmap.parse(
        dedent(
            f"""\
            {header}
            dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>


            """
        )
    )

    assert len(mailmap.records) == 1
    assert (
        mailmap.records[0].canonical
        == "dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>"
    )
    assert mailmap.records[0].aliases == set()
    assert mailmap.records[0].pre_comment == header

    # Add a new record by hand.
    new_contributor = "AA BB <aa@bb.example.org>"
    mailmap.records.append(Record(canonical=new_contributor))

    assert mailmap.render() == (
        header
        + "\n"
        + new_contributor
        + "\n"
        + "dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>"
    )


def test_sync_mailmap_reports_a_git_failure(tmp_path, monkeypatch, hermetic_git):
    """Outside a git repository the command fails with git's own message."""
    monkeypatch.chdir(tmp_path)

    result = CliRunner().invoke(repomatic, ["sync-mailmap"])

    assert result.exit_code == 1
    assert "Error" in result.output
    assert not (tmp_path / ".mailmap").exists()


def test_strip_generated_header_reads_what_generated_header_writes():
    """The reader drops exactly the block the writer stamps."""
    body = "# Format is:\nKiwi <kiwi@example.com>"
    stamped = generated_header("repomatic sync-mailmap") + body
    assert strip_generated_header(stamped) == body


def test_render_leaves_the_records_untouched():
    """Rendering twice gives the same text: the top comment is not consumed."""
    mailmap = Mailmap()
    mailmap.parse(
        "# Fruit stand.\nMelon <melon@example.com>\nApricot <a@example.com>\n"
    )

    first = mailmap.render()

    assert mailmap.render() == first
    assert first == (
        "# Fruit stand.\nApricot <a@example.com>\nMelon <melon@example.com>"
    )


def test_update_from_git_matches_identities_without_case(monkeypatch):
    """A contributor matching a record in another case is not added again."""
    mailmap = Mailmap()
    mailmap.parse("Kiwi Fruit <kiwi@example.com> Kiwi <KIWI@example.com>\n")
    monkeypatch.setattr(
        "repomatic.mailmap.list_contributor_identities",
        lambda: {
            "kiwi <kiwi@example.com>",
            "Melon <melon@example.com>",
            "MELON <melon@example.com>",
        },
    )

    mailmap.update_from_git()

    assert [record.canonical for record in mailmap.records] == [
        "Kiwi Fruit <kiwi@example.com>",
        "MELON <melon@example.com>",
    ]


def test_update_from_git_raises_on_a_git_failure(monkeypatch):
    """A failing git call reaches the caller with its message."""

    def fail() -> set[str]:
        msg = "fatal: not a git repository"
        raise RuntimeError(msg)

    monkeypatch.setattr("repomatic.mailmap.list_contributor_identities", fail)
    with pytest.raises(RuntimeError, match="not a git repository"):
        Mailmap().update_from_git()
